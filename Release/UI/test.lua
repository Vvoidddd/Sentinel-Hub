-- UI-only smoke test: button, toggle, collapse, RightShift, and Unload.
local UI = loadstring(game:HttpGet(
    "https://raw.githubusercontent.com/Vvoidddd/Sentinel-Hub/main/Release/UI/SentinelUI.lua"
))()
local window = UI.CreateWindow(Enum.KeyCode.RightShift)
local tab = window:CreateTab("Home")
tab:Label("Your Sentinel workspace. Choose a tab above to explore.")
tab:Button("Test notification", function()
    print("Button works")
end)
tab:Toggle("Preview toggle", false, function(enabled)
    print("Toggle:", enabled)
end)
local settings = window:CreateTab("Settings")
settings:Label("Right Shift shows or hides the window. Use - to collapse and Unload to close.")
settings:Toggle("Enabled example", true, function(enabled)
    print("Enabled example:", enabled)
end)
settings:Button("Unload Sentinel", function()
    window:Destroy()
end)
